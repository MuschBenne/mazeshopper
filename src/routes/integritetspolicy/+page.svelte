            Den är märkt <code>httpOnly</code> och kan inte läsas av JavaScript i webbläsaren.
        </p>
    </section>

    <section>
        <h2>8. Dina rättigheter</h2>
        <p>Du har följande rättigheter enligt GDPR:</p>
        <ul>
            <li><strong>Tillgång</strong> — rätt att få veta vilka uppgifter vi har om dig.</li>
            <li><strong>Rättelse</strong> — rätt att korrigera felaktiga uppgifter (e-postadress kan ändras under Inställningar).</li>
            <li><strong>Radering</strong> — rätt att radera ditt konto och all tillhörande data (finns under Inställningar → Fara-zon).</li>
            <li><strong>Begränsning</strong> — rätt att begära att vi begränsar behandlingen av dina uppgifter.</li>
            <li><strong>Portabilitet</strong> — rätt att få ut dina uppgifter i ett strukturerat, maskinläsbart format.</li>
            <li><strong>Invändning</strong> — rätt att invända mot behandling som grundar sig på berättigat intresse.</li>
        </ul>
        <p>
            För att utöva dina rättigheter, kontakta oss på <a href="mailto:benjamin@rosenbergab.com">benjamin@rosenbergab.com</a>.
            Vi svarar inom 30 dagar.
        </p>
    </section>

