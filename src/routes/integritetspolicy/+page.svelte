    <section>
        <h2>1. Personuppgiftsansvarig</h2>
        <p>
            MazeShopper ägs och drivs av <strong>Benjamin Sjöstrand</strong>.<br>
            Kontakt: <a href="mailto:benjamin@rosenbergab.com">benjamin@rosenbergab.com</a>
        </p>
        <p>
            Vi är personuppgiftsansvarig för den behandling av personuppgifter som beskrivs i denna policy.
        </p>
    </section>

    <section>
        <h2>2. Vilka uppgifter vi behandlar</h2>
        <ul>
            <li><strong>Användarnamn</strong> — används för att identifiera ditt konto och visas för andra användare du delar listor med.</li>
            <li><strong>E-postadress</strong> — används för att skicka länk vid lösenordsåterställning.</li>
            <li><strong>Lösenord</strong> — lagras i krypterad form (bcrypt). Vi kan aldrig läsa ditt lösenord i klartext.</li>
            <li><strong>Inköpslistor och varor</strong> — innehåll du skapar i tjänsten.</li>
            <li><strong>Varuhusinformation och butiksrutter</strong> — butiker och rutter du konfigurerar.</li>
            <li><strong>Listmallar</strong> — återkommande inköpslistor du sparar.</li>
            <li><strong>Kategoriinställningar</strong> — personliga kategorier och färger.</li>
            <li><strong>Inloggningsuppgifter (session)</strong> — en slumpmässig token lagras i en cookie för att hålla dig inloggad.</li>
        </ul>
    </section>

    <section>
        <h2>3. Åldersgräns</h2>
        <p>
            Tjänsten riktar sig till personer som är <strong>16 år eller äldre</strong>. Vi samlar inte
            medvetet in uppgifter om barn under 16 år. Om du känner till att ett barn under 16 år har
            skapat ett konto, kontakta oss så raderar vi kontot.
        </p>
    </section>

    <section>
        <h2>4. Ändamål och rättslig grund</h2>
        <p>
            Vi behandlar dina uppgifter för att kunna tillhandahålla tjänsten MazeShopper åt dig.
            Den rättsliga grunden är <strong>avtal</strong> (Art. 6.1.b GDPR) — behandlingen är nödvändig
            för att fullgöra det avtal som ingås när du skapar ett konto.
        </p>
    </section>

    <section>
        <h2>5. Hur länge vi lagrar uppgifterna</h2>
        <ul>
            <li><strong>Kontouppgifter</strong> (användarnamn, e-post, lösenord, listor, varuhus, inställningar) — tills du raderar ditt konto.</li>
            <li><strong>Session-cookie</strong> — 30 dagar, eller tills du loggar ut.</li>
            <li><strong>Tokens för lösenordsåterställning</strong> — 15 minuter, raderas automatiskt därefter.</li>
        </ul>
    </section>

    <section>
        <h2>6. Tredje parter och underbiträden</h2>
        <p>Vi anlitar följande tjänster för att driva MazeShopper:</p>
        <ul>
            <li>
                <strong>MongoDB Atlas</strong> (databas) — lagrar all din data.
                MongoDB är ett amerikanskt bolag; dataöverföring till USA sker med stöd av
                EU–US Data Privacy Framework eller standardavtalsklausuler.
            </li>
            <li>
                <strong>Resend</strong> (e-postleverantör, USA) — används enbart för att skicka e-post vid lösenordsåterställning.
                Din e-postadress delas med Resend enbart för detta ändamål.
                Dataöverföring till USA sker med stöd av EU–US Data Privacy Framework eller standardavtalsklausuler.
            </li>
            <li>
                <strong>Vercel</strong> (hosting, USA) — webbapplikationen körs på Vercels infrastruktur.
                Dataöverföring till USA sker med stöd av EU–US Data Privacy Framework eller standardavtalsklausuler.
            </li>
        </ul>
        <p>Vi säljer aldrig dina personuppgifter till tredje part.</p>
    </section>

    <section>
